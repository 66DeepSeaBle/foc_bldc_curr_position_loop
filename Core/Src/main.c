/**
  ******************************************************************************
  * @file    main.c
  * @brief   程序入口 —— 全部逻辑都在下面三个函数里, 这里只做"调用"。
  ******************************************************************************
  *
  *  分层(见 board_config.h 头部注释):
  *    main.c  → app.c(应用) → sensor_hall.c(传感器) / foc_control.c(控制律)
  *            ↘ bsp_stm32g4.c(平台: 唯一碰 HAL/寄存器的地方)
  *
  ******************************************************************************
  */
#include "main.h"
#include "bsp.h"
#include "app.h"

/**
  * @brief  HAL 出错时的兜底: 关中断停住(便于调试器挂上看现场)。
  */
void Error_Handler(void)
{
    __disable_irq();
    while (1) {
    }
}

int main(void)
{
    /* 1) 平台层: 时钟 + GPIO/ADC/TIM/OPAMP/UART + 调试输出通道 */
    BSP_Init();

    /* 2) 应用层: 参数装配 → FOC 初始化 → 启动功率级/采样 → 零电流标定 →
          状态机待机 → 帮助信息 → 波形输出启动 */
    App_Init();

    /* 3) 主循环: 按键 / 日志上报 / 手动霍尔验证 / 10ms 节拍 */
    while (1) {
        App_Loop();
    }
}
